#!/usr/bin/env python3
"""Writes packaging/ROS_BUILD_STATUS.md: the build.ros2.org binary build badges
of every MRPT package, per ROS 2 distribution and platform.

The packages are those with a package.xml under modules/, apps/ and
mrpt_examples_cpp/. Edit DISTROS when ROS distributions or their platforms
change.

Usage: scripts/generate_ros_build_status.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "packaging" / "ROS_BUILD_STATUS.md"
JOBS_URL = "https://build.ros2.org/job"

# (distro, Ubuntu version, [(platform label, job prefix, job platform), ...])
DISTROS = [
    ("Humble", "22.04", [
        ("amd64", "Hbin_uJ64", "ubuntu_jammy_amd64"),
        ("arm64", "Hbin_ujv8_uJv8", "ubuntu_jammy_arm64"),
    ]),
    ("Jazzy", "24.04", [
        ("amd64", "Jbin_uN64", "ubuntu_noble_amd64"),
        ("arm64", "Jbin_unv8_uNv8", "ubuntu_noble_arm64"),
        ("RHEL 9", "Jbin_rhel_el964", "rhel_9_x86_64"),
    ]),
    ("Kilted", "24.04", [
        ("amd64", "Kbin_uN64", "ubuntu_noble_amd64"),
        ("arm64", "Kbin_unv8_uNv8", "ubuntu_noble_arm64"),
        ("RHEL 9", "Kbin_rhel_el964", "rhel_9_x86_64"),
    ]),
    ("Lyrical", "26.04", [
        ("amd64", "Lbin_uR64", "ubuntu_resolute_amd64"),
        ("arm64", "Lbin_armv8_uRv8", "ubuntu_resolute_arm64"),
        ("RHEL 10", "Lbin_rhel_el1064", "rhel_10_x86_64"),
        ("Fedora 43", "Lbin_fedora_fc4364", "fedora_43_x86_64"),
    ]),
    ("Rolling", "26.04", [
        ("amd64", "Rbin_uR64", "ubuntu_resolute_amd64"),
        ("arm64", "Rbin_unv8_uRv8", "ubuntu_resolute_arm64"),
        ("RHEL 10", "Rbin_rhel_el1064", "rhel_10_x86_64"),
        ("Fedora 44", "Rbin_fedora_fc4464", "fedora_44_x86_64"),
    ]),
]


def package_names():
    files = []
    for pattern in ("modules/*/package.xml", "apps/*/package.xml",
                    "mrpt_examples_cpp/package.xml"):
        files += ROOT.glob(pattern)
    names = []
    for f in files:
        if (f.parent / "COLCON_IGNORE").exists():
            continue
        text = f.read_text(encoding="utf-8")
        names.append(text.split("<name>", 1)[1].split("</name>", 1)[0].strip())
    return sorted(names)


def badge(label, job):
    url = f"{JOBS_URL}/{job}/"
    return f"{label} [![{label}]({url}badge/icon)]({url})"


def main():
    header = ["Package"] + [f"{d} <br> (Ubuntu {u})" for d, u, _ in DISTROS]
    lines = [
        "# ROS 2 build farm status of MRPT packages",
        "",
        "<!-- Generated by scripts/generate_ros_build_status.py: "
        "do not edit by hand. -->",
        "",
        "Binary builds of each MRPT package on "
        "[build.ros2.org](https://build.ros2.org/), per ROS 2 distribution "
        "and platform. A red badge means the package currently fails to "
        "build on that platform; a platform not listed is not offered by "
        "that distribution.",
        "",
        "See the [README](../README.md#ros-2) for installation instructions "
        "and the per-distribution summary.",
        "",
        "| " + " | ".join(header) + " |",
        "|" + " --- |" * len(header),
    ]
    for pkg in package_names():
        cells = [f"`{pkg}`"]
        for _, _, platforms in DISTROS:
            cells.append(" <br> ".join(
                badge(label, f"{prefix}__{pkg}__{platform}__binary")
                for label, prefix, platform in platforms))
        lines.append("| " + " | ".join(cells) + " |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
