TEST(CImage_JPEG, DecoderSwitch)
{
  {
    JpegDecoderScope scope(false);
    EXPECT_FALSE(CImage::getUseLibJpegTurbo());
  }
  {
    JpegDecoderScope scope(true);
    EXPECT_EQ(CImage::getUseLibJpegTurbo(), CImage::hasLibJpegTurbo());
  }
}

// Runs with whichever decoder is active, so it is meaningful in both builds:
TEST(CImage_JPEG, DecodesColorAndGray)
{
  for (const bool useTurbo : {false, true})
  {
    const auto color = decode(encodeJPEG(makeTestImage(mrpt::img::CH_RGB)), useTurbo);
    ASSERT_TRUE(color.has_value());
    EXPECT_EQ(color->getWidth(), 97);
    EXPECT_EQ(color->getHeight(), 61);
    EXPECT_EQ(color->channels(), mrpt::img::CH_RGB);
    // Against the original: lossy encoding (measured: up to 16 levels, 2.0 on average)
    expectSimilar(*color, makeTestImage(mrpt::img::CH_RGB), 24, 3.0);

    const auto gray = decode(kJpegGray24x16, useTurbo);
    ASSERT_TRUE(gray.has_value());
    EXPECT_EQ(gray->getWidth(), 24);
    EXPECT_EQ(gray->getHeight(), 16);
    EXPECT_EQ(gray->channels(), mrpt::img::CH_GRAY);

    const auto progressive = decode(kJpegProgressive420_24x16, useTurbo);
    ASSERT_TRUE(progressive.has_value());
    EXPECT_EQ(progressive->getWidth(), 24);
    EXPECT_EQ(progressive->channels(), mrpt::img::CH_RGB);
  }
}

