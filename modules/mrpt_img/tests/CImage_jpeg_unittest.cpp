/** Sets the JPEG decoder for its scope, then restores the previous one. */
class JpegDecoderScope
{
 public:
  explicit JpegDecoderScope(bool useTurbo) : m_prev(CImage::getUseLibJpegTurbo())
  {
    CImage::setUseLibJpegTurbo(useTurbo);
  }
  ~JpegDecoderScope() { CImage::setUseLibJpegTurbo(m_prev); }
  JpegDecoderScope(const JpegDecoderScope&) = delete;
  JpegDecoderScope& operator=(const JpegDecoderScope&) = delete;
  JpegDecoderScope(JpegDecoderScope&&) = delete;
  JpegDecoderScope& operator=(JpegDecoderScope&&) = delete;

 private:
  bool m_prev;
};

