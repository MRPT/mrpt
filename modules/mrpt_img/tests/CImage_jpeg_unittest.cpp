/** Smooth gradients plus some texture, so JPEG keeps detail in every channel. */
CImage makeTestImage(TImageChannels ch, int w = 97, int h = 61)
{
  CImage img(w, h, ch);
  for (int y = 0; y < h; y++)
  {
    auto* row = img.ptrLine<uint8_t>(y);
    for (int x = 0; x < w; x++)
    {
      const int texture = ((x / 4 + y / 4) % 2) * 40;
      for (int c = 0; c < static_cast<int>(ch); c++)
      {
        row[x * static_cast<int>(ch) + c] =
            static_cast<uint8_t>((x * 2 + y * (c + 1) + texture + 60 * c) % 256);
      }
    }
  }
  return img;
}

// stb_image_write keeps full chroma resolution (4:4:4) above quality 90, and
// subsamples it (4:2:0) otherwise.
std::vector<uint8_t> encodeJPEG(const CImage& img, int quality = 95)
{
  mrpt::io::CMemoryStream s;
  img.saveToStreamAsJPEG(s, quality);
  const auto* p = static_cast<const uint8_t*>(s.getRawBufferData());
  return {p, p + s.getTotalBytesCount()};
}

std::optional<CImage> decode(
    const std::vector<uint8_t>& jpeg, bool useTurbo, TImageChannels ch = mrpt::img::CH_AS_IS)
{
  JpegDecoderScope scope(useTurbo);
  CImage img;
  if (!img.loadFromEncodedBuffer(jpeg.data(), jpeg.size(), ch))
  {
    return std::nullopt;
  }
  return img;
}

/** Same geometry and layout; pixels within tolerance. The defaults are for two
 * JPEG decoders on the same file: measured with libjpeg-turbo 2.1 vs stb_image,
 * at most 3 levels apart, and below 0.1 on average. */
void expectSimilar(const CImage& a, const CImage& b, int maxAbsDiff = 4, double maxMeanDiff = 0.25)
{
  ASSERT_EQ(a.getWidth(), b.getWidth());
  ASSERT_EQ(a.getHeight(), b.getHeight());
  ASSERT_EQ(a.channels(), b.channels());
  ASSERT_EQ(a.getPixelDepth(), PixelDepth::D8U);
  ASSERT_EQ(b.getPixelDepth(), PixelDepth::D8U);

  const int nValues = a.getWidth() * static_cast<int>(a.channels());
  int worst = 0;
  double sum = 0;
  for (int y = 0; y < static_cast<int>(a.getHeight()); y++)
  {
    const auto* ra = a.ptrLine<uint8_t>(y);
    const auto* rb = b.ptrLine<uint8_t>(y);
    for (int i = 0; i < nValues; i++)
    {
      const int d = std::abs(static_cast<int>(ra[i]) - static_cast<int>(rb[i]));
      worst = std::max(worst, d);
      sum += d;
    }
  }
  const double mean = sum / (static_cast<double>(nValues) * a.getHeight());
  EXPECT_LE(worst, maxAbsDiff);
  EXPECT_LE(mean, maxMeanDiff);
}
